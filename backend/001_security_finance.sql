create or replace function public.inventory_craft_apply(
  p_user_id bigint,
  p_gift_ids bigint[],
  p_reward jsonb
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare selected_count integer; consumed jsonb; won public.user_gifts%rowtype;
begin
  with d as (
    delete from public.user_gifts where user_id=p_user_id and id=any(p_gift_ids) returning *
  ) select count(*), coalesce(jsonb_agg(to_jsonb(d)),'[]'::jsonb) into selected_count, consumed from d;
  if selected_count <> cardinality(p_gift_ids) then raise exception 'Some gifts were not found'; end if;

  insert into public.user_gifts(user_id,gift_id,gift_name,gift_price,gift_image,withdraw_available_at,created_at)
