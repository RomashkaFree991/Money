create or replace function public.pending_prize_resolve(p_user_id bigint, p_action text)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare p public.user_pending_prizes%rowtype; g public.user_gifts%rowtype; new_balance numeric;
begin
  if p_action not in ('sell','claim') then raise exception 'Bad action'; end if;
  delete from public.user_pending_prizes where user_id=p_user_id returning * into p;
  if not found then raise exception 'Prize not found'; end if;

  if p_action='sell' then
    select public.add_win_balance(p_user_id,coalesce(p.gift_price,0)::integer) into new_balance;
    return jsonb_build_object('prize',to_jsonb(p),'newBalance',new_balance,'claimedGift',null);
  end if;

  insert into public.user_gifts(user_id,gift_id,gift_name,gift_price,gift_image,withdraw_available_at,created_at)
  values(p_user_id,p.gift_id,p.gift_name,p.gift_price,p.gift_image,now()+interval '20 minutes',now())
  returning * into g;
  select balance into new_balance from public.users where id=p_user_id;
  return jsonb_build_object('prize',to_jsonb(p),'newBalance',coalesce(new_balance,0),'claimedGift',to_jsonb(g));
end;
$$;

