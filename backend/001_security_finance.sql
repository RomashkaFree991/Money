  returning * into won;
  return jsonb_build_object('consumed',consumed,'wonGift',to_jsonb(won));
end;
$$;

create or replace function public.withdraw_claim_for_transfer(p_intent_id uuid, p_user_id bigint)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare w public.withdraw_intents%rowtype; g public.user_gifts%rowtype;
begin
  select * into w from public.withdraw_intents where id=p_intent_id and user_id=p_user_id for update;
  if not found then raise exception 'Withdraw intent not found'; end if;
  if w.status='completed' then return w.gift_snapshot; end if;
  if w.status='transferring' then
    if w.gift_snapshot is null then raise exception 'Transfer snapshot missing'; end if;
    return w.gift_snapshot;
  end if;
  if w.status <> 'paid' then raise exception 'Withdraw intent is not paid'; end if;

  delete from public.user_gifts where user_id=p_user_id and id=w.gift_db_id returning * into g;
  if not found then raise exception 'Gift not found'; end if;
  if g.withdraw_available_at is not null and g.withdraw_available_at > now() then
    raise exception 'Gift local hold is active';
  end if;
  if g.tg_msg_id is null and nullif(g.tg_slug,'') is null then
    raise exception 'Exact Telegram gift reference is missing';
  end if;
  if g.tg_is_unique is false then raise exception 'Gift is not unique'; end if;

  update public.withdraw_intents
  set status='transferring',gift_snapshot=to_jsonb(g)
  where id=p_intent_id;
  return to_jsonb(g);
end;
$$;

create or replace function public.withdraw_restore_transfer(p_intent_id uuid, p_user_id bigint)
returns boolean
language plpgsql
security definer
set search_path=public
as $$
declare w public.withdraw_intents%rowtype; j jsonb;
begin
  select * into w from public.withdraw_intents where id=p_intent_id and user_id=p_user_id for update;
  if not found then raise exception 'Withdraw intent not found'; end if;
  if w.status='paid' then return true; end if;
  if w.status <> 'transferring' or w.gift_snapshot is null then raise exception 'Withdraw intent is not transferring'; end if;
  j := w.gift_snapshot;
  insert into public.user_gifts(
    id,user_id,gift_id,gift_name,gift_price,gift_image,withdraw_available_at,tg_msg_id,tg_slug,tg_is_unique,created_at
  ) values (
    (j->>'id')::bigint,(j->>'user_id')::bigint,j->>'gift_id',j->>'gift_name',
    coalesce((j->>'gift_price')::numeric,0),coalesce(j->>'gift_image',''),
    nullif(j->>'withdraw_available_at','')::timestamptz,
    nullif(j->>'tg_msg_id','')::bigint,nullif(j->>'tg_slug',''),
    case when j ? 'tg_is_unique' and j->>'tg_is_unique' <> '' then (j->>'tg_is_unique')::boolean else null end,
    coalesce(nullif(j->>'created_at','')::timestamptz,now())
  ) on conflict (id) do nothing;
  update public.withdraw_intents set status='paid' where id=p_intent_id;
  return true;
end;
$$;

create or replace function public.withdraw_mark_completed(p_intent_id uuid, p_user_id bigint)
returns boolean
language plpgsql
security definer
set search_path=public
as $$
declare w public.withdraw_intents%rowtype;
begin
  select * into w from public.withdraw_intents where id=p_intent_id and user_id=p_user_id for update;
  if not found or w.status not in ('transferring','completed') then
    raise exception 'Withdraw intent cannot be completed';
  end if;
  if w.status='transferring' then
    update public.withdraw_intents
    set status='completed',completed_at=coalesce(completed_at,now())
    where id=p_intent_id;
  end if;
  if w.referral_credited_at is null then
    perform public.credit_referral_for_deposit(p_user_id,w.fee_stars);
    update public.withdraw_intents set referral_credited_at=now() where id=p_intent_id;
  end if;
  return true;
end;
$$;

create or replace function public.promo_redeem_atomic(
  p_user_id bigint,
  p_code text,
  p_reward_gift jsonb default null
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  pr public.promo_codes%rowtype;
  used integer := 0;
  reward_stars integer := 0;
  g public.user_gifts%rowtype;
  new_balance numeric;
  reward_id text;
begin
  select * into pr
  from public.promo_codes
  where lower(code)=lower(trim(coalesce(p_code,''))) and active is true
  order by code
  limit 1
  for update;
  if not found then raise exception 'Promo not found'; end if;

  select count(*) into used from public.manual_promo_redemptions
  where user_id=p_user_id and code=pr.code;
  if used >= greatest(1,coalesce(pr.max_uses_per_user,1)) then
    raise exception 'Promo already activated / limit reached';
  end if;

  if pr.reward_gift_id is not null then
    reward_id := coalesce(p_reward_gift->>'id',p_reward_gift->>'giftId');
    if p_reward_gift is null or reward_id is distinct from pr.reward_gift_id then
      raise exception 'Promo gift mismatch';
    end if;
  end if;

  insert into public.manual_promo_redemptions(user_id,code,redeemed_at)
  values(p_user_id,pr.code,now());

  if pr.reward_gift_id is not null then
    insert into public.user_gifts(user_id,gift_id,gift_name,gift_price,gift_image,withdraw_available_at,created_at)
    values(
      p_user_id, reward_id, p_reward_gift->>'name',
      greatest(0,floor(coalesce((p_reward_gift->>'price')::numeric,0))),
      coalesce(p_reward_gift->>'image',''), now()+interval '20 minutes', now()
    ) returning * into g;
    return jsonb_build_object('reward',0,'gift',to_jsonb(g));
  end if;

  reward_stars := greatest(0,floor(coalesce(pr.reward,0))::integer);
  if reward_stars <= 0 then raise exception 'Promo reward is invalid'; end if;
  select public.balance_add(p_user_id,reward_stars) into new_balance;
  return jsonb_build_object('reward',reward_stars,'balance',coalesce(new_balance,0),'gift',null);
end;
$$;

create or replace function public.admin_adjust_balance(p_user_id bigint, p_delta integer)
returns numeric
language plpgsql
security definer
set search_path=public
as $$
declare current_balance numeric; new_balance numeric;
begin
  if p_user_id is null or p_user_id <= 0 or p_delta is null or p_delta = 0 then
    raise exception 'Bad balance adjustment';
  end if;
  select balance into current_balance from public.users where id=p_user_id for update;
  if not found then raise exception 'User not found'; end if;
  new_balance := greatest(0,coalesce(current_balance,0)+p_delta);
  update public.users set balance=new_balance,updated_at=now() where id=p_user_id;
  return new_balance;
end;
$$;

create or replace function public.apply_telegram_star_payment(
  p_charge_id text,
  p_provider_charge_id text,
  p_invoice_id uuid,
  p_user_id bigint,
  p_amount integer,
  p_currency text,
  p_payload jsonb
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare inserted boolean := false; rc integer := 0; new_balance numeric;
begin
  if p_currency <> 'XTR' then raise exception 'Bad currency'; end if;
  if p_amount <= 0 then raise exception 'Bad amount'; end if;

  insert into public.payment_receipts(telegram_charge_id,provider_charge_id,invoice_id,user_id,kind,amount,currency,payload)
  values(p_charge_id,p_provider_charge_id,p_invoice_id,p_user_id,'deposit',p_amount,p_currency,p_payload)
  on conflict do nothing;
  get diagnostics rc = row_count;
  inserted := rc > 0;

  if inserted then
    select public.balance_add(p_user_id,p_amount) into new_balance;
    perform public.credit_referral_for_deposit(p_user_id,p_amount);
  else
    if not exists (
      select 1 from public.payment_receipts
      where kind='deposit' and user_id=p_user_id and amount=p_amount and currency=p_currency
        and (telegram_charge_id=p_charge_id or invoice_id=p_invoice_id)
    ) then
      raise exception 'Conflicting payment receipt';
    end if;
    select balance into new_balance from public.users where id=p_user_id;
  end if;
  return jsonb_build_object('applied',inserted,'balance',coalesce(new_balance,0));
end;
$$;

create or replace function public.apply_withdraw_fee_payment(
  p_charge_id text,
  p_provider_charge_id text,
  p_intent_id uuid,
  p_user_id bigint,
  p_amount integer,
  p_currency text,
  p_payload jsonb
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare w public.withdraw_intents%rowtype; inserted boolean := false; rc integer := 0;
begin
  select * into w from public.withdraw_intents where id=p_intent_id and user_id=p_user_id for update;
  if not found then raise exception 'Withdraw intent not found'; end if;
  if w.expires_at < now() and w.status='created' then
    update public.withdraw_intents set status='expired' where id=p_intent_id;
    raise exception 'Withdraw intent expired';
  end if;
  if p_currency <> 'XTR' or p_amount <> w.fee_stars then raise exception 'Payment mismatch'; end if;

  if w.status in ('paid','transferring','completed','refunded') then
    if w.telegram_charge_id = p_charge_id then
      return jsonb_build_object('applied',false,'status',w.status);
    end if;
    raise exception 'Withdraw intent already paid';
  end if;
  if w.status <> 'created' then raise exception 'Withdraw intent is not payable'; end if;

  insert into public.payment_receipts(telegram_charge_id,provider_charge_id,withdraw_intent_id,user_id,kind,amount,currency,payload)
  values(p_charge_id,p_provider_charge_id,p_intent_id,p_user_id,'withdraw',p_amount,p_currency,p_payload)
  on conflict do nothing;
  get diagnostics rc = row_count;
  inserted := rc > 0;

  if inserted then
    update public.withdraw_intents set status='paid',telegram_charge_id=p_charge_id,paid_at=now() where id=p_intent_id;
  else
    if not exists (
      select 1 from public.payment_receipts
      where kind='withdraw' and withdraw_intent_id=p_intent_id and telegram_charge_id=p_charge_id
        and user_id=p_user_id and amount=p_amount and currency=p_currency
    ) then
      raise exception 'Conflicting withdraw payment receipt';
    end if;
  end if;
  return jsonb_build_object('applied',inserted,'status',(select status from public.withdraw_intents where id=p_intent_id));
end;
$$;

create or replace function public.apply_ton_deposit(p_intent_id uuid, p_tx_hash text)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare i public.ton_deposit_intents%rowtype; new_balance numeric;
begin
  select * into i from public.ton_deposit_intents where id=p_intent_id for update;
  if not found then raise exception 'TON intent not found'; end if;
  if i.status='credited' then
    select balance into new_balance from public.users where id=i.user_id;
    return jsonb_build_object('applied',false,'balance',coalesce(new_balance,0),'amount',i.stars_amount);
  end if;
  if i.status <> 'created' then raise exception 'TON intent is not creditable'; end if;
  if i.expires_at < now() - interval '2 minutes' then raise exception 'TON intent expired'; end if;
  if exists(select 1 from public.ton_deposit_intents where tx_hash=p_tx_hash and id<>p_intent_id) then
    raise exception 'TON transaction already used';
  end if;

  update public.ton_deposit_intents set status='credited',tx_hash=p_tx_hash,credited_at=now() where id=p_intent_id;
  select public.balance_add(i.user_id,i.stars_amount) into new_balance;
  perform public.credit_referral_for_deposit(i.user_id,i.stars_amount);
  return jsonb_build_object('applied',true,'balance',coalesce(new_balance,0),'amount',i.stars_amount);
end;
$$;

create or replace function public.credit_relayer_gift(
  p_msg_id bigint,
  p_user_id bigint,
  p_gift jsonb,
  p_slug text,
  p_is_unique boolean
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare rc integer := 0; g public.user_gifts%rowtype; price integer;
begin
  if p_msg_id is null or p_msg_id <= 0 then raise exception 'msg_id required'; end if;
  insert into public.relayer_gift_receipts(msg_id,user_id,gift_id)
  values(p_msg_id,p_user_id,coalesce(p_gift->>'id',p_gift->>'giftId'))
  on conflict (msg_id) do nothing;
  get diagnostics rc = row_count;
  if rc = 0 then return jsonb_build_object('duplicate',true); end if;

  price := greatest(0, floor(coalesce((p_gift->>'price')::numeric,0))::integer);
  insert into public.user_gifts(user_id,gift_id,gift_name,gift_price,gift_image,withdraw_available_at,tg_msg_id,tg_slug,tg_is_unique,created_at)
  values(p_user_id,p_gift->>'id',p_gift->>'name',price,p_gift->>'image',now()+interval '20 minutes',p_msg_id,p_slug,p_is_unique,now())
  returning * into g;

  if price > 0 then
    update public.users set total_deposited=coalesce(total_deposited,0)+price,updated_at=now() where id=p_user_id;
    perform public.credit_referral_for_deposit(p_user_id,price);
  end if;
  return jsonb_build_object('duplicate',false,'gift',to_jsonb(g));
end;
$$;

