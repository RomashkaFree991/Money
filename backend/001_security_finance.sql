-- 53-bit cryptographically random unit interval [0,1).
create or replace function public.secure_random_unit()
returns double precision
language plpgsql
volatile
as $$
declare
  b bytea := gen_random_bytes(8);
  n numeric := 0;
  i integer;
begin
  for i in 0..7 loop
    n := n * 256 + get_byte(b, i);
  end loop;
  n := mod(n, 9007199254740992::numeric);
  return (n / 9007199254740992::numeric)::double precision;
end;
$$;

create or replace function public.sample_crash_target_secure()
returns double precision
language plpgsql
volatile
as $$
declare
  r double precision := public.secure_random_unit();
  x double precision;
begin
  if r < 0.55 then x := 1.01 + public.secure_random_unit() * 0.49;
  elsif r < 0.85 then x := 1.50 + public.secure_random_unit() * 1.00;
  elsif r < 0.95 then x := 2.50 + public.secure_random_unit() * 1.50;
  elsif r < 0.99 then x := 4.00 + public.secure_random_unit() * 3.00;
  else x := 7.00 + public.secure_random_unit() * 8.00;
  end if;
  return round(x::numeric, 2)::double precision;
end;
$$;

create or replace function public.crash_sync_state()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  s public.crash_state%rowtype;
  now_ts timestamptz := clock_timestamp();
  target double precision;
  duration_ms integer;
  hist jsonb;
begin
  insert into public.crash_state(id, round_id, phase, countdown_ends_at, crash_multiplier, growth_ms, history)
  values (1, 1, 'countdown', now_ts + interval '10 seconds', public.sample_crash_target_secure(), 8000, '[]'::jsonb)
  on conflict (id) do nothing;

  select * into s from public.crash_state where id = 1 for update;

  loop
    if s.phase = 'countdown' and now_ts >= s.countdown_ends_at then
      s.phase := 'live';
      s.live_start_at := s.countdown_ends_at;
      duration_ms := greatest(400, round(s.growth_ms * ln(greatest(s.crash_multiplier, 1.01)))::integer);
      s.crash_at := s.live_start_at + (duration_ms::text || ' milliseconds')::interval;
      update public.crash_state set
        phase=s.phase, live_start_at=s.live_start_at, crash_at=s.crash_at, updated_at=now_ts
      where id=1;
    elsif s.phase = 'live' and s.crash_at is not null and now_ts >= s.crash_at then
      s.phase := 'ended';
      s.next_round_at := s.crash_at + interval '3 seconds';
      hist := jsonb_build_array(jsonb_build_object('roundId', s.round_id, 'multiplier', round(s.crash_multiplier::numeric,2))) || coalesce(s.history,'[]'::jsonb);
      s.history := (
        select coalesce(jsonb_agg(value), '[]'::jsonb)
        from (select value from jsonb_array_elements(hist) with ordinality t(value, ord) where ord <= 12 order by ord) q
      );
      update public.crash_state set
        phase=s.phase, next_round_at=s.next_round_at, history=s.history, updated_at=now_ts
      where id=1;
    elsif s.phase = 'ended' and s.next_round_at is not null and now_ts >= s.next_round_at then
      target := public.sample_crash_target_secure();
      s.round_id := s.round_id + 1;
      s.phase := 'countdown';
      s.countdown_ends_at := now_ts + interval '10 seconds';
      s.live_start_at := null;
      s.crash_at := null;
      s.crash_multiplier := target;
      s.next_round_at := null;
      update public.crash_state set
        round_id=s.round_id, phase=s.phase, countdown_ends_at=s.countdown_ends_at,
        live_start_at=null, crash_at=null, crash_multiplier=target, next_round_at=null,
        updated_at=now_ts
      where id=1;
    else
      exit;
    end if;
    select * into s from public.crash_state where id=1;
  end loop;

  return jsonb_build_object(
    'roundId', s.round_id,
    'phase', s.phase,
    'countdownEndsAt', extract(epoch from s.countdown_ends_at) * 1000,
    'liveStartAt', case when s.live_start_at is null then 0 else extract(epoch from s.live_start_at) * 1000 end,
    'crashAt', case when s.crash_at is null then 0 else extract(epoch from s.crash_at) * 1000 end,
    'crashMultiplier', s.crash_multiplier,
    'nextRoundAt', case when s.next_round_at is null then 0 else extract(epoch from s.next_round_at) * 1000 end,
    'growthMs', s.growth_ms,
    'history', s.history
  );
end;
$$;

create or replace function public.crash_place_bet(
  p_user_id bigint,
  p_first_name text,
  p_photo_url text,
  p_amount integer
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  s jsonb;
  rid bigint;
  new_balance numeric;
begin
  if p_amount is null or p_amount <= 0 then raise exception 'Bad amount'; end if;
  s := public.crash_sync_state();
  if s->>'phase' <> 'countdown' then raise exception 'Round already started'; end if;
  rid := (s->>'roundId')::bigint;

  if exists(select 1 from public.crash_bets where round_id=rid and user_id=p_user_id) then
    raise exception 'Bet already placed';
  end if;
  if exists(select 1 from public.user_pending_prizes where user_id=p_user_id) then
    raise exception 'Resolve pending prize first';
  end if;

  select public.spend_balance(p_user_id, p_amount) into new_balance;
  insert into public.crash_bets(round_id,user_id,first_name,photo_url,amount)
  values(rid,p_user_id,p_first_name,p_photo_url,p_amount);

  return jsonb_build_object('roundId',rid,'newBalance',new_balance);
end;
$$;

create or replace function public.crash_settle_bet(
  p_user_id bigint,
  p_round_id bigint,
  p_awarded_gift jsonb default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  s public.crash_state%rowtype;
  b public.crash_bets%rowtype;
  now_ts timestamptz := clock_timestamp();
  mult double precision;
  pay integer;
  new_balance numeric;
  gift_id text;
  gift_name text;
  gift_image text;
begin
  perform public.crash_sync_state();
  select * into s from public.crash_state where id=1 for update;
  if s.round_id <> p_round_id or s.phase <> 'live' or s.crash_at is null or now_ts >= s.crash_at then
    raise exception 'Round is not live';
  end if;

  select * into b from public.crash_bets where round_id=p_round_id and user_id=p_user_id for update;
  if not found then raise exception 'No active bet'; end if;
  if b.cashed_out then raise exception 'Already cashed out'; end if;

  mult := exp(greatest(0, extract(epoch from (now_ts - s.live_start_at)) * 1000) / s.growth_ms);
  mult := least(mult, s.crash_multiplier);
  pay := greatest(0, floor(b.amount * mult)::integer);

  update public.crash_bets set cashed_out=true,payout=pay,cashed_out_at=now_ts,awarded_gift=p_awarded_gift
  where round_id=p_round_id and user_id=p_user_id;

  if p_awarded_gift is not null and pay > 0 then
    gift_id := coalesce(p_awarded_gift->>'id', p_awarded_gift->>'giftId');
    gift_name := p_awarded_gift->>'name';
    gift_image := p_awarded_gift->>'image';
    if gift_id is null or gift_name is null or gift_image is null then raise exception 'Bad awarded gift'; end if;
    delete from public.user_pending_prizes where user_id=p_user_id;
    insert into public.user_pending_prizes(user_id,gift_id,gift_name,gift_price,gift_image,created_at)
    values(p_user_id,gift_id,gift_name,pay,gift_image,now_ts);
    select balance into new_balance from public.users where id=p_user_id;
  elsif pay > 0 then
    select public.add_win_balance(p_user_id, pay) into new_balance;
  else
    select balance into new_balance from public.users where id=p_user_id;
  end if;

  return jsonb_build_object('payout',pay,'newBalance',coalesce(new_balance,0));
end;
$$;

create or replace function public.link_signed_tg_username(p_user_id bigint, p_username text)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare uname text := lower(regexp_replace(trim(coalesce(p_username,'')), '^@', ''));
begin
  if p_user_id is null or p_user_id <= 0 or uname = '' then raise exception 'Bad Telegram identity'; end if;
  -- initData proves that this username currently belongs to p_user_id; update both sides atomically.
  delete from public.tg_username_links where user_id=p_user_id or username=uname;
  insert into public.tg_username_links(username,user_id,updated_at) values(uname,p_user_id,now());
  return jsonb_build_object('username',uname,'userId',p_user_id);
end;
$$;

